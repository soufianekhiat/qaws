using System.IO;
using Sharpmake;

namespace Qaws
{
    [Generate]
    public class QawsLibProject : CommonProject
    {
        public QawsLibProject()
        {
            Name = "Qaws";
            SourceRootPath = @"[project.SharpmakeCsPath]\..\..\..\src\qaws";

            // Both precisions in one library (docs/parameter_convention_plan.md):
            // every source is compiled through two wrappers generated here, one
            // per precision, never directly (MSBuild does not rebuild an object
            // whose source includes another of the project's sources when that
            // one changes); qaws_names.h keeps the two sets apart. The
            // precision-free sources, the status strings and the memory module
            // (the process and thread allocators, the arena: one state for
            // both precisions), are compiled by the f64 pass only.
            string src = Path.GetFullPath(Path.Combine(SharpmakeCsPath, "..", "..", "..", "src", "qaws"));
            string dir = Path.GetFullPath(Path.Combine(SharpmakeCsPath, "..", "..", "..", "tmp", "qaws_precision"));
            Directory.CreateDirectory(dir);
            foreach (string file in Directory.GetFiles(src, "*.c", SearchOption.AllDirectories))
            {
                string name = Path.GetFileNameWithoutExtension(file);
                foreach (int bits in new int[] { 32, 64 })
                {
                    if ((name == "qaws_status" || name == "qaws_internal_memory") && bits == 32)
                        continue;
                    string wrapper = Path.Combine(dir, name + "_f" + bits + ".c");
                    string text = "/* generated by QawsLib.cs: " + name + ".c as f" + bits + " */\n#undef QAWS_SCALAR_IS_FLOAT\n#define QAWS_SCALAR_IS_FLOAT "
                        + (bits == 32 ? "1" : "0") + "\n#include \"" + file.Replace('\\', '/') + "\"\n";
                    if (!File.Exists(wrapper) || File.ReadAllText(wrapper) != text)
                        File.WriteAllText(wrapper, text);
                    SourceFiles.Add(wrapper);
                }
            }
        }

        [Configure()]
        public override void ConfigureAll(Configuration conf, QawsTarget target)
        {
            base.ConfigureAll(conf, target);

            // Output type: Static library
            conf.Output = Configuration.OutputType.Lib;

            // Include paths
            conf.IncludePaths.Add(@"[project.SharpmakeCsPath]\..\..\..\src\qaws");

            // Source files (explicitly list them for now)
            conf.SourceFilesBuildExcludeRegex.Add(@".*\.sharpmake\.cs$");

            // The library holds both precisions, in every configuration: its
            // sources are compiled through the wrappers only (each sets its
            // precision); the configuration's scalar only sets what callers'
            // unsuffixed names mean.
            conf.SourceFilesBuildExcludeRegex.Add(@"[\\/]src[\\/]qaws[\\/].*\.c$");
            conf.Defines.Remove("QAWS_SCALAR_IS_FLOAT=1");
            conf.Defines.Remove("QAWS_SCALAR_IS_FLOAT=0");
            conf.Defines.Add("QAWS_SCALAR_IS_FLOAT=0");
            conf.AdditionalCompilerOptions.Add("/wd4305");  // (the f32 objects: truncation from 'double' to 'float')
            conf.AdditionalCompilerOptions.Add("/wd4244");  // (conversion from 'double' to 'float')
        }
    }
}
